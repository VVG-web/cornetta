#!/usr/bin/env python3
"""Generate both app localization files from localization/strings.json.

Usage:
  scripts/localization.py          write generated files
  scripts/localization.py --check  fail if generated files are stale or invalid
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "localization" / "strings.json"
SWIFT = ROOT / "Sources" / "CornettaCore" / "LocalizedStrings.generated.swift"
CSHARP = ROOT / "windows" / "src" / "Cornetta.App" / "LocalizedStrings.generated.cs"
STRINGS_DIR = ROOT / "Sources" / "Cornetta" / "Resources"
PLACEHOLDER = re.compile(r"\{(\d+)\}")
KEY = re.compile(r"^[a-z][A-Za-z0-9]*(\.[a-z][A-Za-z0-9]*)+$")


def load() -> dict[str, dict[str, str]]:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    if set(data) != {"strings"}:
        sys.exit("strings.json must contain exactly one top-level 'strings' object")
    strings = data["strings"]
    seen_italian: dict[str, tuple[str, str]] = {}
    for name, value in strings.items():
        validate(name, value, seen_italian)
    return strings


def validate(name: str, value: dict[str, str], seen_italian: dict[str, tuple[str, str]]) -> None:
    if not KEY.fullmatch(name):
        sys.exit(f"Invalid localization key: {name}")
    if set(value) != {"it", "en"}:
        sys.exit(f"{name} must define exactly 'it' and 'en'")
    if not value["it"].strip() or not value["en"].strip():
        sys.exit(f"{name} has an empty translation")
    if value["it"] != value["it"].strip() or value["en"] != value["en"].strip():
        sys.exit(f"{name} has leading or trailing whitespace")
    previous = seen_italian.get(value["it"])
    if previous and previous[1] != value["en"]:
        sys.exit(f"Italian text is ambiguous: {name} and {previous[0]}")
    seen_italian[value["it"]] = (name, value["en"])
    placeholders = {int(index) for index in PLACEHOLDER.findall(value["it"])}
    if placeholders != {int(index) for index in PLACEHOLDER.findall(value["en"])}:
        sys.exit(f"{name} uses different placeholders in Italian and English")
    if placeholders and placeholders != set(range(max(placeholders) + 1)):
        sys.exit(f"{name} placeholders must be sequential from {{0}}")


def swift_case(name: str) -> str:
    parts = re.split(r"[.]", name)
    return parts[0] + "".join(part[:1].upper() + part[1:] for part in parts[1:])


def csharp_case(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[.]", name))


def swift_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def csharp_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def strings_file(language: str, strings: dict[str, dict[str, str]]) -> str:
    lines = ["/* Generated by scripts/localization.py. Do not edit. */", ""]
    written = set()
    for name in sorted(strings):
        key = strings[name]["it"]
        value = key if language == "it" else strings[name]["en"]
        # Static SwiftUI localization uses no placeholders. Formatting is handled by L10n.format.
        if PLACEHOLDER.search(key) or key in written:
            continue
        written.add(key)
        lines.append(f'"{escape_strings(key)}" = "{escape_strings(value)}";')
    return "\n".join(lines) + "\n"


def escape_strings(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def swift_source(strings: dict[str, dict[str, str]]) -> str:
    lines = [
        "// Generated by scripts/localization.py. Do not edit.",
        "import Foundation",
        "",
        "public enum L10nKey: String, CaseIterable, Sendable {",
    ]
    for name in sorted(strings):
        lines.append(f'    case {swift_case(name)} = "{name}"')
    lines += [
        "}",
        "",
        "public enum L10n {",
        "    private static let italian: [L10nKey: String] = [",
    ]
    for name in sorted(strings):
        lines.append(f"        .{swift_case(name)}: {swift_string(strings[name]['it'])},")
    lines += [
        "    ]",
        "",
        "    private static let english: [L10nKey: String] = [",
    ]
    for name in sorted(strings):
        lines.append(f"        .{swift_case(name)}: {swift_string(strings[name]['en'])},")
    lines += [
        "    ]",
        "",
        "    public static func text(_ key: L10nKey, language: AppLanguage) -> String {",
        "        (language == .italian ? italian : english)[key]!",
        "    }",
        "",
        "    public static func format(_ key: L10nKey, language: AppLanguage, _ arguments: CVarArg...) -> String {",
        "        format(key, language: language, arguments: arguments)",
        "    }",
        "",
        "    public static func format(_ key: L10nKey, language: AppLanguage, arguments: [CVarArg]) -> String {",
        "        let raw = text(key, language: language)",
        "        var format = raw.replacingOccurrences(of: \"%\", with: \"%%\")",
        "        for index in stride(from: arguments.count - 1, through: 0, by: -1) {",
        "            format = format.replacingOccurrences(of: \"{\\(index)}\", with: \"%\\(index + 1)$@\")",
        "        }",
        "        return String(format: format, locale: language.locale, arguments: arguments)",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def csharp_source(strings: dict[str, dict[str, str]]) -> str:
    lines = [
        "// Generated by scripts/localization.py. Do not edit.",
        "using System;",
        "using System.Collections.Generic;",
        "using System.Globalization;",
        "",
        "namespace Cornetta.App",
        "{",
        "    internal enum L10nKey",
        "    {",
    ]
    for name in sorted(strings):
        lines.append(f"        {csharp_case(name)},")
    lines += [
        "    }",
        "",
        "    internal static class L10n",
        "    {",
        "        private static readonly Dictionary<L10nKey, string> Italian = new Dictionary<L10nKey, string>",
        "        {",
    ]
    for name in sorted(strings):
        lines.append(f"            {{ L10nKey.{csharp_case(name)}, {csharp_string(strings[name]['it'])} }},")
    lines += [
        "        };",
        "",
        "        private static readonly Dictionary<L10nKey, string> English = new Dictionary<L10nKey, string>",
        "        {",
    ]
    for name in sorted(strings):
        lines.append(f"            {{ L10nKey.{csharp_case(name)}, {csharp_string(strings[name]['en'])} }},")
    lines += [
        "        };",
        "",
        "        public static string Text(L10nKey key) => Text(key, AppLanguageSettings.Current);",
        "",
        "        public static string Text(L10nKey key, AppLanguage language) =>",
        "            (language == AppLanguage.English ? English : Italian)[key];",
        "",
        "        public static string Format(L10nKey key, params object[] arguments) =>",
        "            string.Format(CultureInfo.CurrentCulture, Text(key), arguments);",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def outputs(strings: dict[str, dict[str, str]]) -> dict[Path, str]:
    result = {
        SWIFT: swift_source(strings),
        CSHARP: csharp_source(strings),
        STRINGS_DIR / "it.lproj" / "Localizable.strings": strings_file("it", strings),
        STRINGS_DIR / "en.lproj" / "Localizable.strings": strings_file("en", strings),
    }
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    generated = outputs(load())
    stale = []
    for path, content in generated.items():
        if options.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        for path in stale:
            print(f"Out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        sys.exit("Run scripts/localization.py and commit the generated files.")
    if options.check:
        print(f"Localization catalog valid: {len(generated)} files generated from one source.")
    else:
        print(f"Generated {len(generated)} localization files.")


if __name__ == "__main__":
    main()
